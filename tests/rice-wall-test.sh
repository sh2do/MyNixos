#!/usr/bin/env bash
# Tests for modules/theme/rice-wall.sh (run: bash tests/rice-wall-test.sh)
cd "$(dirname "$0")/.." || exit 1
source tests/lib.sh
RICE_WALL=$PWD/modules/theme/rice-wall.sh

# rice-wall writes into Firefox profiles and Vencord's settings under $HOME,
# so every test gets a home of its own.
eval "lib_$(declare -f setup_sandbox)"
setup_sandbox() {
  lib_setup_sandbox
  export HOME=$TMP/home
  unset XDG_CONFIG_HOME
  mkdir -p "$HOME"
}

walls() { for w in "$@"; do : > "$RICE_WALL_DIR/$w"; done; }

test_next_wraps() {
  stub awww; stub matugen
  walls a.jpg b.jpg c.jpg
  echo "$RICE_WALL_DIR/c.jpg" > "$RICE_STATE_DIR/current"
  bash "$RICE_WALL" next
  assert_eq "$(cat "$RICE_STATE_DIR/current")" "$RICE_WALL_DIR/a.jpg"
}

test_next_calls_awww_then_matugen() {
  stub awww; stub matugen
  walls a.jpg b.jpg
  echo "$RICE_WALL_DIR/a.jpg" > "$RICE_STATE_DIR/current"
  bash "$RICE_WALL" next
  local calls; calls=$(cat "$TMP/calls")
  assert_eq "$(sed -n 1p "$TMP/calls" | cut -d' ' -f1-3)" "awww img $RICE_WALL_DIR/b.jpg"
  assert_contains "$calls" "--transition-type fade"
  assert_contains "$(sed -n 2p "$TMP/calls")" "matugen image $RICE_WALL_DIR/b.jpg -t scheme-content --prefer saturation -m dark"
}

test_set_missing_path_fails() {
  stub awww; stub matugen
  local err code=0
  err=$(bash "$RICE_WALL" set "$TMP/nope.jpg" 2>&1 >/dev/null) || code=$?
  assert_eq "$code" "1"
  assert_contains "$err" "no such wallpaper"
}

test_matugen_failure_keeps_colours() {
  stub awww; stub matugen 1
  walls a.jpg b.jpg
  echo "$RICE_WALL_DIR/a.jpg" > "$RICE_STATE_DIR/current"
  echo '{"primary":"KEEP"}' > "$RICE_STATE_DIR/colors.json"
  local err code=0
  err=$(bash "$RICE_WALL" next 2>&1 >/dev/null) || code=$?
  assert_eq "$code" "0"
  assert_contains "$(cat "$RICE_STATE_DIR/colors.json")" "KEEP"
  assert_eq "$(cat "$RICE_STATE_DIR/current")" "$RICE_WALL_DIR/b.jpg"
  assert_contains "$err" "keeping previous colours"
}

test_init_without_awww() {
  stub awww; stub matugen
  walls b.jpg a.jpg
  bash "$RICE_WALL" init
  assert_eq "$(cat "$RICE_STATE_DIR/current")" "$RICE_WALL_DIR/a.jpg"
  ! grep -q '^awww' "$TMP/calls"
  grep -q '^matugen image' "$TMP/calls"
}

test_current_prints_path() {
  stub awww; stub matugen
  echo "$RICE_WALL_DIR/x.jpg" > "$RICE_STATE_DIR/current"
  assert_eq "$(bash "$RICE_WALL" current)" "$RICE_WALL_DIR/x.jpg"
}

test_set_grow_transition() {
  stub awww; stub matugen
  walls a.jpg
  RICE_TRANSITION=grow bash "$RICE_WALL" set "$RICE_WALL_DIR/a.jpg"
  assert_contains "$(sed -n 1p "$TMP/calls")" "--transition-type grow --transition-pos center"
}

# Firefox and Vencord: rice-wall spreads what matugen wrote after it runs.
app_home() {
  mkdir -p "$RICE_STATE_DIR/firefox"
  echo '/* Generated by rice-wall (matugen). chrome */' > "$RICE_STATE_DIR/firefox/userChrome.css"
  echo '/* Generated by rice-wall (matugen). content */' > "$RICE_STATE_DIR/firefox/userContent.css"
}

profiles_ini() { # DIR then "Path IsRelative" pairs
  local dir=$1 i=0; shift
  mkdir -p "$dir"
  printf '[General]\nStartWithLastProfile=1\nVersion=2\n\n' > "$dir/profiles.ini"
  while [ $# -gt 0 ]; do
    printf '[Profile%s]\nName=p%s\nIsRelative=%s\nPath=%s\n\n' "$i" "$i" "$2" "$1" >> "$dir/profiles.ini"
    i=$((i + 1)); shift 2
  done
}

test_firefox_profiles_get_css() {
  stub awww; stub matugen; app_home
  walls a.jpg
  local xdg=$HOME/.config/mozilla/firefox old=$HOME/.mozilla/firefox abs=$TMP/elsewhere/abs.profile
  profiles_ini "$xdg" "kyykv2no.default" 1 "$abs" 0
  profiles_ini "$old" "Profiles/zz.default-release" 1
  mkdir -p "$xdg/kyykv2no.default" "$abs" "$old/Profiles/zz.default-release"
  bash "$RICE_WALL" init
  for p in "$xdg/kyykv2no.default" "$abs" "$old/Profiles/zz.default-release"; do
    assert_contains "$(cat "$p/chrome/userChrome.css")" "chrome"
    assert_contains "$(cat "$p/chrome/userContent.css")" "content"
  done
}

test_firefox_missing_profile_dir_is_skipped() {
  stub awww; stub matugen; app_home
  walls a.jpg
  profiles_ini "$HOME/.config/mozilla/firefox" "gone.default" 1
  bash "$RICE_WALL" init
  [ ! -e "$HOME/.config/mozilla/firefox/gone.default" ]
}

test_firefox_keeps_users_own_css() {
  stub awww; stub matugen; app_home
  walls a.jpg
  local p=$HOME/.config/mozilla/firefox/mine.default
  profiles_ini "$HOME/.config/mozilla/firefox" "mine.default" 1
  mkdir -p "$p/chrome"
  echo '#nav-bar { mine: 1 }' > "$p/chrome/userChrome.css"
  local err
  err=$(bash "$RICE_WALL" init 2>&1 >/dev/null)
  assert_eq "$(cat "$p/chrome/userChrome.css")" '#nav-bar { mine: 1 }'
  assert_contains "$(cat "$p/chrome/userContent.css")" "content"
  assert_contains "$err" "leaving your own"
}

test_firefox_untouched_when_matugen_fails() {
  stub awww; stub matugen 1; app_home
  walls a.jpg
  profiles_ini "$HOME/.config/mozilla/firefox" "a.default" 1
  mkdir -p "$HOME/.config/mozilla/firefox/a.default"
  bash "$RICE_WALL" init 2>/dev/null
  [ ! -e "$HOME/.config/mozilla/firefox/a.default/chrome" ]
}

test_vencord_theme_enabled_once() {
  stub awww; stub matugen; app_home
  walls a.jpg
  local s=$HOME/.config/Vencord/settings/settings.json
  mkdir -p "$(dirname "$s")"
  echo '{"enabledThemes":["other.css"],"plugins":{"x":{"enabled":true}}}' > "$s"
  bash "$RICE_WALL" init
  assert_eq "$(jq -c .enabledThemes "$s")" '["other.css","rice.css"]'
  assert_eq "$(jq -c .plugins "$s")" '{"x":{"enabled":true}}'
  # Turned off by hand: rice-wall leaves it off.
  echo '{"enabledThemes":[]}' > "$s"
  bash "$RICE_WALL" init
  assert_eq "$(jq -c .enabledThemes "$s")" '[]'
}

test_vencord_settings_created_when_missing() {
  stub awww; stub matugen; app_home
  walls a.jpg
  bash "$RICE_WALL" init
  assert_eq "$(jq -c .enabledThemes "$HOME/.config/Vencord/settings/settings.json")" '["rice.css"]'
}

test_vencord_bad_settings_left_alone() {
  stub awww; stub matugen; app_home
  walls a.jpg
  local s=$HOME/.config/Vencord/settings/settings.json
  mkdir -p "$(dirname "$s")"
  echo 'not json' > "$s"
  bash "$RICE_WALL" init 2>/dev/null
  assert_eq "$(cat "$s")" 'not json'
}

for t in test_set_grow_transition test_next_wraps test_next_calls_awww_then_matugen test_set_missing_path_fails \
  test_matugen_failure_keeps_colours test_init_without_awww test_current_prints_path \
  test_firefox_profiles_get_css test_firefox_missing_profile_dir_is_skipped test_firefox_keeps_users_own_css \
  test_firefox_untouched_when_matugen_fails test_vencord_theme_enabled_once test_vencord_settings_created_when_missing \
  test_vencord_bad_settings_left_alone; do
  run_test "$t"
done
finish
