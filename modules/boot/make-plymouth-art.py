#!/usr/bin/env python3
"""Writes the art for the rice-pond Plymouth theme (modules/boot/theme/):

  pond.svg  the still pond, seen from above: stone rim, pebbles, a lily pad;
  koi.svg   two koi nose to tail along a ring, the same size as the pond, so
            rotating the whole image about its centre makes them swim round
            (the spinner);
  haze.svg  a soft glow behind the scene, so the dark raven's outline reads;
  prompt.svg, bead.svg  the passphrase card (pond glass with drips) and the
            drop shown for each typed character.

The raven is modules/umbriel/raven-art/art.svg, used as it is (the theme's
derivation drops its background). The fish come from the fastfetch koi
generator (modules/theme/make-koi-svg.py) with its colours fixed to the rice's
dark purple-blue tones: Plymouth runs before login, so matugen's colours
aren't there.

Run: python3 modules/boot/make-plymouth-art.py
"""
import importlib.util
import sys

sys.dont_write_bytecode = True  # no __pycache__ in modules/theme
import math
import os
import random

HERE = os.path.dirname(os.path.abspath(__file__))
spec = importlib.util.spec_from_file_location(
    "koi_art", os.path.join(HERE, "..", "theme", "make-koi-svg.py"))
K = importlib.util.module_from_spec(spec)
spec.loader.exec_module(K)

# The fixed palette (the generator's functions read K.C).
K.C.update({
    "surface": "#100f17",
    "deep": "#191725",
    "rim": "#2a2638",
    "white": "#e8e2f0",
    "primary": "#c3b6ee",
    "pad": "#463c66",
    "tertiary": "#e6b4cc",
    "outline": "#8a83a2",
})
C = K.C
f = K.f
SIZE = 200  # design units; rendered at 400 px


def head(view, extra_defs=""):
    return [f'<svg xmlns="http://www.w3.org/2000/svg" viewBox="0 0 {view} {view}" width="{view * 2}" height="{view * 2}">',
            "  <!-- Generated by modules/boot/make-plymouth-art.py; edit that, not this. -->",
            "<defs>",
            '<filter id="soft" x="-30%" y="-30%" width="160%" height="160%"><feGaussianBlur stdDeviation="1.6"/></filter>',
            '<filter id="edge"><feGaussianBlur stdDeviation="0.22"/></filter>',
            '<filter id="deep" x="-20%" y="-20%" width="140%" height="140%"><feGaussianBlur stdDeviation="0.9"/></filter>',
            extra_defs,
            "</defs>"]


def pond():
    cx = cy = SIZE / 2
    r = 88.0
    out = head(SIZE,
               f'<radialGradient id="water" cx="0.42" cy="0.38" r="0.75"><stop offset="0" stop-color="{C["rim"]}"/>'
               f'<stop offset="0.55" stop-color="{C["deep"]}"/><stop offset="1" stop-color="{C["surface"]}"/></radialGradient>'
               '<radialGradient id="vignette" cx="0.5" cy="0.5" r="0.5"><stop offset="0.72" stop-color="black" stop-opacity="0"/>'
               '<stop offset="1" stop-color="black" stop-opacity="0.5"/></radialGradient>'
               '<linearGradient id="padshine" x1="0" y1="0" x2="1" y2="1"><stop offset="0" stop-color="white" stop-opacity="0.18"/>'
               '<stop offset="1" stop-color="black" stop-opacity="0.15"/></linearGradient>'
               f'<clipPath id="pond"><circle cx="{cx}" cy="{cy}" r="{r}"/></clipPath>')
    rnd = random.Random(11)
    out.append(f'<circle cx="{cx}" cy="{cy}" r="{r + 4}" fill="{C["rim"]}"/>')
    for i in range(40):
        a = 2 * math.pi * (i + rnd.random() * 0.4) / 40
        rr = r + 4 + rnd.uniform(-1, 1)
        x, y = cx + math.cos(a) * rr, cy + math.sin(a) * rr
        out.append(f'<ellipse cx="{f(x)}" cy="{f(y)}" rx="{f(rnd.uniform(4, 6.5))}" ry="{f(rnd.uniform(2.6, 3.6))}" '
                   f'transform="rotate({f(math.degrees(a) + 90)} {f(x)} {f(y)})" fill="{C["rim"]}" '
                   f'stroke="{C["outline"]}" stroke-opacity="0.4" stroke-width="0.5"/>')
    out.append(f'<circle cx="{cx}" cy="{cy}" r="{r}" fill="url(#water)"/>')
    out.append('<g clip-path="url(#pond)">')
    out.append('<g filter="url(#deep)" opacity="0.35">')
    for i in range(55):
        a, rr = rnd.uniform(0, 2 * math.pi), r * math.sqrt(rnd.random())
        out.append(f'<ellipse cx="{f(cx + math.cos(a) * rr)}" cy="{f(cy + math.sin(a) * rr)}" rx="{f(rnd.uniform(1, 2.6))}" '
                   f'ry="{f(rnd.uniform(0.8, 1.8))}" fill="{C["outline"]}" fill-opacity="{f(rnd.uniform(0.2, 0.6))}"/>')
    out.append("</g>")
    # Faint caustic light on the surface.
    for i in range(13):
        y = 22 + i * 12 + rnd.uniform(-3, 3)
        x0 = rnd.uniform(14, 120)
        seg = [(x0 + k * 6, y + 2.2 * math.sin(k * 1.3 + i)) for k in range(rnd.randint(5, 11))]
        out.append(f'<path d="M {" L ".join(f"{f(x)} {f(yy)}" for x, yy in seg)}" stroke="white" '
                   f'stroke-opacity="0.04" stroke-width="1.2" fill="none" stroke-linecap="round"/>')
    out += K.lily(50, 158, 14, 300)
    out += K.lily(86, 177, 7, 20)
    out += K.flower(46, 155)
    out.append(f'<circle cx="{cx}" cy="{cy}" r="{r}" fill="url(#vignette)"/>')
    out.append("</g>")
    out.append(f'<circle cx="{cx}" cy="{cy}" r="{r}" fill="none" stroke="black" stroke-opacity="0.35" stroke-width="1.2"/>')
    out.append("</svg>")
    return out


def koi():
    """Two koi on a ring of radius ~50 about the centre, swimming
    counterclockwise (the nose leads at the smaller angle)."""
    out = head(SIZE)
    a = K.Fish(r=52, a0=200, sweep=-62, width=17, wave=2.5, phase=0.3, cx=SIZE / 2, cy=SIZE / 2)
    b = K.Fish(r=50, a0=20, sweep=-62, width=16, wave=2.5, phase=2.0, cx=SIZE / 2, cy=SIZE / 2)
    hi, sumi = C["hi"], C["sumi"]
    a_patches = [(a.blob(0.08, 0.0, 0.06, 0.55, 1), hi),
                 (a.blob(0.32, -0.35, 0.11, 0.85, 2), hi),
                 (a.blob(0.55, 0.4, 0.09, 0.75, 3), hi)]
    b_patches = [(b.blob(0.27, 0.3, 0.1, 0.8, 6), hi),
                 (b.blob(0.52, -0.4, 0.08, 0.7, 7), hi),
                 (b.blob(0.2, -0.55, 0.035, 0.35, 8), sumi),
                 (b.blob(0.62, 0.2, 0.04, 0.4, 10), sumi)]
    out += K.koi(a, "ka", C["white"], a_patches, C["sumi"], 0.16)
    out += K.koi(b, "kb", C["primary"], b_patches, "white", 0.22, metallic=True)
    out.append("</svg>")
    return out


def haze():
    out = head(SIZE,
               f'<radialGradient id="glow" cx="0.5" cy="0.5" r="0.5"><stop offset="0" stop-color="{C["pad"]}" stop-opacity="0.55"/>'
               f'<stop offset="0.6" stop-color="{C["pad"]}" stop-opacity="0.16"/><stop offset="1" stop-color="{C["pad"]}" stop-opacity="0"/></radialGradient>')
    out.append(f'<circle cx="{SIZE / 2}" cy="{SIZE / 2}" r="{SIZE / 2}" fill="url(#glow)"/>')
    out.append("</svg>")
    return out


def prompt():
    """The password card, in the bar's glass: a translucent slab with a lit
    top rim and a few static drips hanging under it."""
    w, h, r = 220, 40, 12
    out = [f'<svg xmlns="http://www.w3.org/2000/svg" viewBox="0 0 {w} {h + 18}" width="{w * 2}" height="{(h + 18) * 2}">',
           "  <!-- Generated by modules/boot/make-plymouth-art.py; edit that, not this. -->",
           "<defs>",
           '<linearGradient id="depth" x1="0" y1="0" x2="0" y2="1"><stop offset="0" stop-color="white" stop-opacity="0.08"/>'
           '<stop offset="0.5" stop-color="white" stop-opacity="0"/><stop offset="1" stop-color="black" stop-opacity="0.3"/></linearGradient>',
           '<linearGradient id="rim" x1="0" y1="0" x2="1" y2="0"><stop offset="0" stop-color="white" stop-opacity="0"/>'
           '<stop offset="0.3" stop-color="white" stop-opacity="0.5"/><stop offset="0.6" stop-color="white" stop-opacity="0.2"/>'
           '<stop offset="0.8" stop-color="white" stop-opacity="0.4"/><stop offset="1" stop-color="white" stop-opacity="0"/></linearGradient>',
           f'<linearGradient id="trail" x1="0" y1="0" x2="0" y2="1"><stop offset="0" stop-color="{C["white"]}" stop-opacity="0.05"/>'
           f'<stop offset="1" stop-color="{C["primary"]}" stop-opacity="0.3"/></linearGradient>',
           f'<radialGradient id="bead" cx="0.42" cy="0.38" r="0.62"><stop offset="0" stop-color="{C["white"]}" stop-opacity="0.25"/>'
           f'<stop offset="0.65" stop-color="{C["primary"]}" stop-opacity="0.35"/><stop offset="1" stop-color="{C["surface"]}" stop-opacity="0.7"/></radialGradient>',
           "</defs>"]
    out.append(f'<rect x="0.5" y="0.5" width="{w - 1}" height="{h - 1}" rx="{r}" fill="{C["surface"]}" fill-opacity="0.78" '
               f'stroke="{C["primary"]}" stroke-opacity="0.24" stroke-width="1"/>')
    out.append(f'<rect x="1" y="1" width="{w - 2}" height="{h - 2}" rx="{r - 1}" fill="url(#depth)"/>')
    out.append(f'<rect x="{r + 4}" y="0.6" width="{w - 2 * r - 8}" height="0.9" rx="0.45" fill="url(#rim)"/>')
    # Drips: a run down from the lower edge ending in a bead.
    for x, ln, br in ((34, 7, 2.2), (41, 12, 2.8), (150, 5, 1.8), (183, 10, 2.5)):
        y0 = h - 1.5
        out.append(f'<path d="M {x - 0.7} {y0} C {x - 0.7} {y0 + ln * 0.6} {x - br} {y0 + ln - 1} {x - br} {y0 + ln} '
                   f'A {br} {br} 0 0 0 {x + br} {y0 + ln} C {x + br} {y0 + ln - 1} {x + 0.7} {y0 + ln * 0.6} {x + 0.7} {y0} Z" '
                   f'fill="url(#trail)"/>')
        out.append(f'<circle cx="{x}" cy="{y0 + ln}" r="{br}" fill="url(#bead)" stroke="{C["surface"]}" stroke-opacity="0.5" stroke-width="0.5"/>')
        out.append(f'<ellipse cx="{f(x - br * 0.35)}" cy="{f(y0 + ln - br * 0.4)}" rx="{f(br * 0.36)}" ry="{f(br * 0.24)}" '
                   f'transform="rotate(-30 {f(x - br * 0.35)} {f(y0 + ln - br * 0.4)})" fill="white" fill-opacity="0.85"/>')
    out.append("</svg>")
    return out


def bead():
    """A typed character: a drop of water on the glass."""
    out = ['<svg xmlns="http://www.w3.org/2000/svg" viewBox="0 0 10 10" width="20" height="20">',
           "  <!-- Generated by modules/boot/make-plymouth-art.py; edit that, not this. -->",
           f'<defs><radialGradient id="b" cx="0.4" cy="0.36" r="0.64"><stop offset="0" stop-color="{C["white"]}"/>'
           f'<stop offset="0.6" stop-color="{C["primary"]}"/><stop offset="1" stop-color="{C["pad"]}"/></radialGradient></defs>',
           '<circle cx="5" cy="5" r="3.6" fill="url(#b)"/>',
           '<ellipse cx="3.9" cy="3.8" rx="1.1" ry="0.7" transform="rotate(-30 3.9 3.8)" fill="white" fill-opacity="0.9"/>',
           "</svg>"]
    return out


def main():
    d = os.path.join(HERE, "theme")
    os.makedirs(d, exist_ok=True)
    for name, lines in (("pond.svg", pond()), ("koi.svg", koi()), ("haze.svg", haze()),
                        ("prompt.svg", prompt()), ("bead.svg", bead())):
        with open(os.path.join(d, name), "w") as fh:
            fh.write("\n".join(x for x in lines if x) + "\n")


if __name__ == "__main__":
    main()
