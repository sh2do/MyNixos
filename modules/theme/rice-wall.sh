set -euo pipefail
# rice-wall: owns the current wallpaper and recolours the desktop from it.
#
#   rice-wall init        pick a wallpaper if none is set and generate colours (no awww)
#   rice-wall next        show the next wallpaper in the rotation
#   rice-wall set PATH    show PATH (RICE_TRANSITION=grow grows it in from the centre)
#   rice-wall pick        choose one with rofi (rice-menu wallpaper)
#   rice-wall current     print the current wallpaper path
#
# Colours come from matugen, which writes every themed file listed in its
# config. If matugen fails the wallpaper still changes and the old colours stay.
# Two apps can't be reached through a fixed output path, so rice-wall finishes
# the job: Firefox's userChrome/userContent go into every profile listed in
# profiles.ini, and Vencord gets rice.css switched on once.

state_dir=${RICE_STATE_DIR:-$HOME/.cache/rice}
wall_dir=${RICE_WALL_DIR:-$HOME/.local/share/wallpapers/rotation}
matugen_config=${RICE_MATUGEN_CONFIG:-$HOME/.config/matugen/config.toml}
current_file=$state_dir/current

die() {
  echo "rice-wall: $*" >&2
  exit 1
}

rotation() {
  find -L "$wall_dir" -maxdepth 1 -type f \( -iname '*.jpg' -o -iname '*.jpeg' -o -iname '*.png' -o -iname '*.webp' \) | sort
}

current() {
  [ -s "$current_file" ] && cat "$current_file"
}

recolour() {
  if ! matugen image "$1" -t scheme-content --prefer saturation -m dark -c "$matugen_config" >/dev/null; then
    echo "rice-wall: matugen failed, keeping previous colours" >&2
    return 0
  fi
  firefox_css
  vencord_theme
}

# Firefox keeps profiles under ~/.mozilla/firefox (older) or
# $XDG_CONFIG_HOME/mozilla/firefox (newer), with random names, so read
# profiles.ini. A userChrome.css we didn't write is the user's: leave it.
firefox_css() {
  local src=$state_dir/firefox base line path dir css
  [ -d "$src" ] || return 0
  for base in "$HOME/.mozilla/firefox" "${XDG_CONFIG_HOME:-$HOME/.config}/mozilla/firefox"; do
    [ -f "$base/profiles.ini" ] || continue
    while IFS= read -r line; do
      line=${line%$'\r'}
      case $line in Path=*) path=${line#Path=} ;; *) continue ;; esac
      case $path in /*) dir=$path ;; *) dir=$base/$path ;; esac
      [ -d "$dir" ] || continue
      mkdir -p "$dir/chrome"
      for css in userChrome.css userContent.css; do
        [ -f "$src/$css" ] || continue
        if [ -e "$dir/chrome/$css" ] && ! grep -q 'Generated by rice-wall' "$dir/chrome/$css"; then
          echo "rice-wall: leaving your own $dir/chrome/$css" >&2
          continue
        fi
        cp -f "$src/$css" "$dir/chrome/$css"
      done
    done < "$base/profiles.ini"
  done
}

# matugen writes ~/.config/Vencord/themes/rice.css; switch it on in Vencord's
# settings the first time only, so turning it off in Discord sticks.
vencord_theme() {
  local marker=$state_dir/vencord-enabled
  local settings=${XDG_CONFIG_HOME:-$HOME/.config}/Vencord/settings/settings.json
  [ -e "$marker" ] && return 0
  mkdir -p "$(dirname "$settings")"
  if [ ! -s "$settings" ]; then
    echo '{"enabledThemes":["rice.css"]}' > "$settings"
  elif jq '.enabledThemes = ((.enabledThemes // []) - ["rice.css"] + ["rice.css"])' "$settings" > "$settings.rice-tmp" 2>/dev/null; then
    mv -f "$settings.rice-tmp" "$settings"
  else
    rm -f "$settings.rice-tmp"
    echo "rice-wall: can't read $settings, enable rice.css in Vencord by hand" >&2
    return 0
  fi
  : > "$marker"
}

show() {
  local wall=$1
  [ -f "$wall" ] || die "no such wallpaper: $wall"
  mkdir -p "$state_dir"
  echo "$wall" > "$current_file"
  local transition=(--transition-type fade --transition-duration 1.2)
  if [ "${RICE_TRANSITION:-}" = grow ]; then
    transition=(--transition-type grow --transition-pos center --transition-duration 1.4)
  fi
  awww img "$wall" "${transition[@]}" --resize crop ||
    echo "rice-wall: awww failed (is awww-daemon running?)" >&2
  recolour "$wall"
}

next() {
  local now first="" found=0 wall
  now=$(current || true)
  while IFS= read -r wall; do
    [ -z "$first" ] && first=$wall
    if [ "$found" = 1 ]; then
      show "$wall"
      return
    fi
    [ "$wall" = "$now" ] && found=1
  done < <(rotation)
  [ -n "$first" ] || die "no wallpapers in $wall_dir"
  show "$first"
}

init() {
  local wall
  wall=$(current || true)
  if [ -z "$wall" ] || [ ! -f "$wall" ]; then
    wall=$(rotation | head -n 1)
    [ -n "$wall" ] || die "no wallpapers in $wall_dir"
    mkdir -p "$state_dir"
    echo "$wall" > "$current_file"
  fi
  recolour "$wall"
}

case ${1:-} in
  init) init ;;
  next) next ;;
  set) show "${2:?usage: rice-wall set PATH}" ;;
  pick) exec rice-menu wallpaper ;;
  current) current || die "no wallpaper set" ;;
  *)
    echo "usage: rice-wall {init|next|set PATH|pick|current}" >&2
    exit 2
    ;;
esac
